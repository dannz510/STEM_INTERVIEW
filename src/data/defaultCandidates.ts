import { Candidate, Department } from '../types';

export function parseDepartments(rawText: string): Department[] {
  const depts: Department[] = [];
  const text = (rawText || '').toLowerCase();
  
  if (text.includes('kỹ thuật') || text.includes('kĩ thuật') || text.includes('ky thuat')) {
    depts.push('ky_thuat');
  }
  if (text.includes('đối ngoại') || text.includes('doi ngoai')) {
    depts.push('doi_ngoai');
  }
  if (text.includes('truyền thông') || text.includes('truyen thong')) {
    depts.push('truyen_thong');
  }
  if (text.includes('hậu cần') || text.includes('hau can')) {
    depts.push('hau_can');
  }
  
  // Default to Technical if empty
  return depts.length > 0 ? depts : ['ky_thuat'];
}

